"""Optional system hardening offered by the setup script. Currently: automatic security updates.

Uses Debian's own mechanism (the unattended-upgrades package driven by apt's daily systemd timers).
Two small files are written, both removable to undo the step:
  /etc/apt/apt.conf.d/20auto-upgrades          turns the daily run on (the standard Debian file)
  /etc/apt/apt.conf.d/52rwsols-auto-updates    adds the Raspberry Pi package sources and the reboot choice
"""
from .errors import SetupError

PACKAGE = 'unattended-upgrades'
PERIODIC_PATH = '/etc/apt/apt.conf.d/20auto-upgrades'
PERIODIC_CONF = ('APT::Periodic::Update-Package-Lists "1";\n'
                 'APT::Periodic::Unattended-Upgrade "1";\n')
EXTRA_PATH = '/etc/apt/apt.conf.d/52rwsols-auto-updates'
TIMERS = ('apt-daily.timer', 'apt-daily-upgrade.timer')
REBOOT_TIME = '04:00'


def render_extra_conf(auto_reboot=False):
    """The package's default configuration only covers Debian's own archives. Raspberry Pi OS also ships
    packages (kernel, firmware, Pi tools) from Raspberry Pi's archive, and the 32-bit OS takes everything
    from Raspbian, which has no separate security archive. List entries add to the default ones."""
    out = [
        '// Generated by RWSOLS setup.py (automatic security updates). Delete this file to undo.',
        'Unattended-Upgrade::Origins-Pattern {',
        '        "origin=Raspberry Pi Foundation,codename=${distro_codename},label=Raspberry Pi Foundation";',
        '        "origin=Raspbian,codename=${distro_codename},label=Raspbian";',
        '};',
    ]
    if auto_reboot:
        out += [
            'Unattended-Upgrade::Automatic-Reboot "true";',
            'Unattended-Upgrade::Automatic-Reboot-Time "%s";' % REBOOT_TIME,
        ]
    return '\n'.join(out) + '\n'


def _apt_value(dump, key):
    for line in dump.splitlines():
        if line.startswith(key + ' '):
            return line[len(key):].strip().rstrip(';').strip('"')
    return None


def auto_updates_status(runner):
    """{'installed': bool, 'enabled': bool, 'auto_reboot': bool}. Read-only."""
    res = runner.run(['dpkg-query', '-W', '-f=${Status}', PACKAGE], check=False, read_only=True)
    installed = res.returncode == 0 and 'install ok installed' in res.stdout
    dump = runner.run(['apt-config', 'dump'], check=False, read_only=True).stdout or ''
    enabled = installed and _apt_value(dump, 'APT::Periodic::Unattended-Upgrade') not in (None, '', '0') \
        and _apt_value(dump, 'APT::Periodic::Update-Package-Lists') not in (None, '', '0')
    return {'installed': installed, 'enabled': enabled,
            'auto_reboot': _apt_value(dump, 'Unattended-Upgrade::Automatic-Reboot') == 'true'}


def enable_auto_updates(runner, auto_reboot=False):
    """Install and switch on unattended upgrades. Raises SetupError if they are not on afterwards."""
    runner.run(['env', 'DEBIAN_FRONTEND=noninteractive', 'apt-get', 'install', '-y', PACKAGE], sudo=True)
    runner.write_file(PERIODIC_PATH, PERIODIC_CONF, '0644')
    runner.write_file(EXTRA_PATH, render_extra_conf(auto_reboot), '0644')
    for timer in TIMERS:
        runner.run(['systemctl', 'enable', '--now', timer], sudo=True)
    if not auto_updates_status(runner)['enabled']:
        raise SetupError('Automatic updates were configured, but apt does not report them as enabled.')


def run_auto_updates_step(runner, ui):
    """Explain, ask, and enable. Returns 'already', 'enabled' or 'declined'. Raises SetupError on failure."""
    if auto_updates_status(runner)['enabled']:
        ui.say('Automatic security updates are already enabled. Nothing to change.')
        return 'already'
    ui.explain('Automatic security updates', [
        'RWSOLS is a web server that can be reached from your network, and possibly from the internet. Security '
        'fixes for Apache, PHP, OpenSSL and the operating system only help once they are installed.',
        'This installs Debian\'s "unattended-upgrades" package and lets it install security updates once a day, '
        'including updates from the Raspberry Pi package archive. Nothing else on the Pi is changed.',
        'To undo it later: delete %s and %s.' % (PERIODIC_PATH, EXTRA_PATH)])
    if not ui.confirm('Install security updates automatically?', True):
        ui.hint('Skipped. Keep the Pi up to date yourself with: sudo apt update && sudo apt full-upgrade')
        return 'declined'
    ui.explain('Automatic restart', [
        'Kernel and firmware updates only take effect after a restart. The Pi can restart itself at %s, only on '
        'days when an installed update needs it. RWSOLS is unavailable for about a minute while it restarts.' % REBOOT_TIME,
        'If you say no, updates are still installed; restart the Pi yourself now and then.'])
    auto_reboot = ui.confirm('Restart automatically at %s when an update needs it?' % REBOOT_TIME, False)
    ui.say('Installing and enabling unattended-upgrades...')
    enable_auto_updates(runner, auto_reboot)
    ui.success('Automatic security updates are on%s.' % (' (with automatic restart at %s)' % REBOOT_TIME if auto_reboot else ''))
    ui.hint('Log: /var/log/unattended-upgrades/unattended-upgrades.log')
    return 'enabled'
