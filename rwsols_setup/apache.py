"""Render and apply the generated Apache configuration (host allowlist + loopback tunnel vhost).

Approach for the allowlist: a server-level <If> section in a conf-enabled file. Server-level
sections are inherited by every <VirtualHost> (including certbot's 000-default-le-ssl.conf), so no
vhost file is edited. A disallowed Host gets "Require all denied" and an ErrorDocument that
internally hands the request to /host_reject.php (which answers 421 with an empty body). The <If>
excludes /host_reject.php itself so the internal redirect cannot loop. No mod_rewrite is needed."""
from .errors import SetupError
from .hosts import LOCALHOST_ENTRIES, validate_hostname

ALLOWED_CONF_NAME = 'rwsols-allowed-hosts'
ALLOWED_CONF_PATH = '/etc/apache2/conf-available/rwsols-allowed-hosts.conf'
TUNNEL_SITE_NAME = 'rwsols-tunnel'
TUNNEL_SITE_PATH = '/etc/apache2/sites-available/rwsols-tunnel.conf'
REJECT_URI = '/host_reject.php'


def regex_escape(host):
    return ''.join(c if (c.isalnum() or c in '-:') else '\\' + c for c in host)


def host_alternation(hosts, allow_localhost=False):
    entries = [validate_hostname(h) for h in hosts]
    if allow_localhost:
        entries += list(LOCALHOST_ENTRIES)
    seen = []
    for e in entries:
        if e not in seen:
            seen.append(e)
    return '|'.join(regex_escape(e) for e in seen)


def host_regex(hosts, allow_localhost=False):
    """PCRE (used with the i flag): lowercase-insensitive, optional single trailing dot, optional :port."""
    return r'^(?:%s)\.?(?::[0-9]+)?$' % host_alternation(hosts, allow_localhost)


def _check_bind(bind, port):
    bind = bind.strip('[]')
    import ipaddress
    try:
        ipaddress.ip_address(bind)
    except ValueError:
        raise SetupError('Tunnel origin bind address %r is not an IP address' % bind)
    if not (isinstance(port, int) and 1 <= port <= 65535):
        raise SetupError('Tunnel origin port %r is invalid' % (port,))
    return bind


def render_allowed_hosts_conf(allowed_hosts, allow_localhost=False, tunnel_hostname=None,
                              access_enabled=False):
    """Return the conf text, or None when nothing is to be enforced (conf should be removed)."""
    allowed_hosts = list(allowed_hosts or [])
    if not allowed_hosts and not access_enabled:
        return None
    out = [
        '# Generated by RWSOLS setup.py from the values in www/html/config.php',
        '# ($ALLOWED_HOSTS, $ALLOW_LOCALHOST, $TUNNEL_HOSTNAME, $ACCESS_*). Do not edit by hand:',
        '# change config.php and re-run `python3 setup.py --remote-access` to regenerate.',
        '#',
        '# Requests whose Host is not listed are handed internally to ' + REJECT_URI + ' (HTTP 421, empty body).',
        '',
    ]
    if allowed_hosts:
        out += [
            '<If "%%{HTTP_HOST} !~ m#%s#i && %%{REQUEST_URI} != \'%s\'">' % (host_regex(allowed_hosts, allow_localhost), REJECT_URI),
            '    Require all denied',
            '    ErrorDocument 403 ' + REJECT_URI,
            '</If>',
            '',
        ]
    if access_enabled:
        if not tunnel_hostname:
            raise SetupError('Access enforcement needs a tunnel hostname')
        cond = '%%{HTTP_HOST} =~ m#%s#i' % host_regex([tunnel_hostname])
        out += [
            '# Cloudflare Access: requests for the tunnel hostname must carry the Access JWT header (PHP verifies',
            '# the signature). The loopback tunnel vhost enforces the same for every Host it receives.',
            '<If "%s && -z req(\'Cf-Access-Jwt-Assertion\') && %%{REQUEST_URI} != \'%s\'">' % (cond, REJECT_URI),
            '    Require all denied',
            '</If>',
            '',
        ]
    return '\n'.join(out)


def render_tunnel_site(bind, port, access_enabled=False):
    bind = _check_bind(bind, port)
    addr = '[%s]' % bind if ':' in bind else bind
    # The listener cannot be identified from a server-level <If> (ap_expr has no local-address
    # variable, and SERVER_PORT can follow the client's Host header), so this rule lives in the vhost.
    access = [
        '        # Cloudflare Access: everything arriving through the tunnel must carry the Access JWT header.',
        '        <If "-z req(\'Cf-Access-Jwt-Assertion\') && %%{REQUEST_URI} != \'%s\'">' % REJECT_URI,
        '                Require all denied',
        '        </If>',
        '',
    ] if access_enabled else []
    return '\n'.join([
        '# Generated by RWSOLS setup.py. Loopback-only listener that cloudflared forwards to.',
        '# The LAN listener (ports.conf) is not touched.',
        'Listen %s:%d' % (addr, port),
        '',
        '<VirtualHost %s:%d>' % (addr, port),
        '        ServerAdmin webmaster@localhost',
        '',
        '        DocumentRoot /var/www/html',
        '        <Directory /var/www/html/>',
        '                AllowOverride AuthConfig FileInfo',
        '                Order allow,deny',
        '                allow from all',
        '                Options -Indexes',
        '        </Directory>',
        '',
        '        # Read by PHP as $_SERVER[\'RWSOLS_TUNNEL_ORIGIN\']; clients cannot forge it.',
        '        SetEnv RWSOLS_TUNNEL_ORIGIN 1',
        '',
    ] + access + [
        '        ErrorLog ${APACHE_LOG_DIR}/tunnel_error.log',
        '        LogLevel error',
        '        CustomLog ${APACHE_LOG_DIR}/tunnel_access.log combined',
        '</VirtualHost>',
        '',
    ])


def _enabled_path(kind, name):
    return '/etc/apache2/%s-enabled/%s.conf' % ({'conf': 'conf', 'site': 'sites'}[kind], name)


def _reload(ctx):
    res = ctx.runner.run(['apache2ctl', 'configtest'], sudo=True, check=False, read_only=True)
    if res.returncode != 0:
        return False, (res.stderr or res.stdout).strip()
    ctx.runner.run(['systemctl', 'reload', 'apache2'], sudo=True)
    return True, ''


def _install(ctx, kind, name, path, content):
    """Write + enable + configtest + reload; roll back the file when configtest fails. Returns True if changed."""
    enabled = ctx.runner.path_exists(_enabled_path(kind, name))
    new = content.encode('utf8')
    prev = ctx.runner.read_file(path)
    if prev == new and enabled:
        return False
    ctx.runner.write_file(path, new, '0644')
    ctx.runner.run(['a2en' + kind, name], sudo=True)
    if ctx.dry_run:
        return True
    ok, msg = _reload(ctx)
    if not ok:
        if prev is None:
            ctx.runner.run(['a2dis' + kind, name], sudo=True, check=False)
            ctx.runner.remove_file(path)
        else:
            ctx.runner.write_file(path, prev, '0644')
        raise SetupError('apache2ctl configtest failed; the previous configuration was restored.\n' + msg)
    return True


def _uninstall(ctx, kind, name, path):
    present = ctx.runner.path_exists(path) or ctx.runner.path_exists(_enabled_path(kind, name))
    if not present:
        return False
    prev = ctx.runner.read_file(path)
    ctx.runner.run(['a2dis' + kind, name], sudo=True, check=False)
    ctx.runner.remove_file(path)
    if ctx.dry_run:
        return True
    ok, msg = _reload(ctx)
    if not ok:
        if prev is not None:
            ctx.runner.write_file(path, prev, '0644')
            ctx.runner.run(['a2en' + kind, name], sudo=True, check=False)
        raise SetupError('apache2ctl configtest failed after removal; restored.\n' + msg)
    return True


def apply_allowed_hosts(ctx, content):
    """content None => remove the conf (legacy behaviour)."""
    if content is None:
        return _uninstall(ctx, 'conf', ALLOWED_CONF_NAME, ALLOWED_CONF_PATH)
    return _install(ctx, 'conf', ALLOWED_CONF_NAME, ALLOWED_CONF_PATH, content)


def apply_tunnel_site(ctx, bind, port, access_enabled=False):
    return _install(ctx, 'site', TUNNEL_SITE_NAME, TUNNEL_SITE_PATH, render_tunnel_site(bind, port, access_enabled))


def remove_tunnel_site(ctx):
    return _uninstall(ctx, 'site', TUNNEL_SITE_NAME, TUNNEL_SITE_PATH)
