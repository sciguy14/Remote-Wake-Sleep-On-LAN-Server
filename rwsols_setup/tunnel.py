ENV_PATH = '/etc/cloudflared/rwsols-tunnel.env'
SERVICE_NAME = 'rwsols-cloudflared'
SERVICE_PATH = '/etc/systemd/system/rwsols-cloudflared.service'
KEYRING_URL = 'https://pkg.cloudflare.com/cloudflare-main.gpg'
KEYRING_PATH = '/usr/share/keyrings/cloudflare-main.gpg'
APT_LIST_PATH = '/etc/apt/sources.list.d/cloudflared.list'
APT_LIST = 'deb [signed-by=/usr/share/keyrings/cloudflare-main.gpg] https://pkg.cloudflare.com/cloudflared any main\n'
DNS_COMMENT = 'Managed by RWSOLS setup.py'
PLACEHOLDER_ID = '<new-tunnel-id>'
SUPPORTED_DEB_ARCH = ('amd64', 'arm64', 'armhf')


def render_env(token):
    return 'TUNNEL_TOKEN=%s\n' % token


def render_unit():
    # Deliberately NOT `cloudflared service install <token>`: that writes the token into a
    # world-readable unit file. Here the token lives in a root-only 0600 EnvironmentFile.
    return '\n'.join([
        '# Generated by RWSOLS setup.py',
        '[Unit]',
        'Description=RWSOLS Cloudflare Tunnel',
        'After=network-online.target',
        'Wants=network-online.target',
        '',
        '[Service]',
        'EnvironmentFile=' + ENV_PATH,
        'ExecStart=/usr/bin/cloudflared --no-autoupdate tunnel run',
        'Restart=on-failure',
        'RestartSec=5s',
        'DynamicUser=yes',
        'NoNewPrivileges=yes',
        'ProtectSystem=strict',
        'ProtectHome=yes',
        'PrivateTmp=yes',
        '',
        '[Install]',
        'WantedBy=multi-user.target',
        '',
    ])


def parse_tunnel_token(token):
    """Tunnel tokens are base64 JSON {"a": account, "t": tunnel id, "s": secret}."""
    try:
        pad = '=' * (-len(token) % 4)
        doc = json.loads(base64.b64decode(token + pad).decode('utf8'))
        if all(k in doc for k in ('a', 't', 's')):
            return {'account_id': doc['a'], 'tunnel_id': doc['t']}
    except (ValueError, UnicodeDecodeError, TypeError):
        pass
    raise SetupError('That does not look like a Cloudflare tunnel token (expected the long base64 string from the dashboard).')


def check_architecture(ctx):
    """cloudflared has no usable build for ARMv6 (Pi Zero / Pi 1); stop early with a clear message."""
    machine = ctx.runner.run(['uname', '-m'], check=False, read_only=True).stdout.strip()
    if machine == 'armv6l':
        raise SetupError('This Pi has an ARMv6 CPU (Pi Zero / Pi 1). Cloudflare does not publish a cloudflared '
                         'build that runs on ARMv6, so Cloudflare Tunnel cannot be used on this device.')
    deb = ctx.runner.run(['dpkg', '--print-architecture'], check=False, read_only=True).stdout.strip()
    if deb and deb not in SUPPORTED_DEB_ARCH:
        raise SetupError('Unsupported CPU architecture %r for cloudflared (supported: %s).' % (deb, ', '.join(SUPPORTED_DEB_ARCH)))


def install_cloudflared(ctx, st):
    """Install from Cloudflare's apt repo (https://pkg.cloudflare.com). Returns True if installed now."""
    check_architecture(ctx)
    if ctx.runner.run(['which', 'cloudflared'], check=False, read_only=True).returncode == 0:
        ctx.ui.say('cloudflared is already installed.')
        return False
    ctx.did('Installing cloudflared from Cloudflare\'s apt repository...', 'install cloudflared from Cloudflare\'s apt repository:')
    key = ctx.http.request('GET', KEYRING_URL)
    if key.status != 200 or not key.body:
        raise SetupError('Could not download the Cloudflare package signing key (HTTP %d).' % key.status)
    ctx.runner.run(['mkdir', '-p', '--mode=0755', '/usr/share/keyrings'], sudo=True)
    ctx.runner.write_file(KEYRING_PATH, key.body, '0644')
    ctx.runner.write_file(APT_LIST_PATH, APT_LIST, '0644')
    ctx.runner.run(['apt-get', 'update'], sudo=True)
    ctx.runner.run(['apt-get', 'install', '-y', 'cloudflared'], sudo=True)
    st['tunnel']['cloudflared_installed_by_wizard'] = True
    return True


def install_service(ctx, token):
    """Write env file (0600) + unit; enable and (re)start. The token only travels via stdin."""
    existing = ctx.runner.read_file(ENV_PATH)
    env_changed = existing != render_env(token).encode('utf8')
    unit_changed = ctx.runner.read_file(SERVICE_PATH) != render_unit().encode('utf8')
    if env_changed:
        ctx.runner.run(['mkdir', '-p', '--mode=0755', '/etc/cloudflared'], sudo=True)
        ctx.runner.write_file(ENV_PATH, render_env(token), '0600')
    if unit_changed:
        ctx.runner.write_file(SERVICE_PATH, render_unit(), '0644')
        ctx.runner.run(['systemctl', 'daemon-reload'], sudo=True)
    active = ctx.runner.run(['systemctl', 'is-active', SERVICE_NAME], check=False, read_only=True).stdout.strip() == 'active'
    if not active:
        ctx.runner.run(['systemctl', 'enable', '--now', SERVICE_NAME], sudo=True)
    elif env_changed or unit_changed:
        ctx.runner.run(['systemctl', 'restart', SERVICE_NAME], sudo=True)
    return env_changed or unit_changed or not active


def remove_service(ctx):
    changed = False
    if ctx.runner.path_exists(SERVICE_PATH) or ctx.runner.path_exists(ENV_PATH):
        ctx.runner.run(['systemctl', 'disable', '--now', SERVICE_NAME], sudo=True, check=False)
        ctx.runner.remove_file(SERVICE_PATH)
        ctx.runner.remove_file(ENV_PATH)
        ctx.runner.run(['systemctl', 'daemon-reload'], sudo=True)
        changed = True
    return changed


def check_origin_port(ctx, st, bind, port):
    """True if the port is free or already served by our own tunnel vhost."""
    if ctx.runner.path_exists(apache._enabled_path('site', apache.TUNNEL_SITE_NAME)):
        prev = st['tunnel']
        if prev.get('origin_port') == port and prev.get('origin_bind') == bind:
            return True
        # The vhost file itself is the evidence, so this still holds when the state file is gone
        # (deleted, or the folder was downloaded again).
        site = ctx.runner.read_file(apache.TUNNEL_SITE_PATH) or b''
        addr = '[%s]' % bind.strip('[]') if ':' in bind else bind
        if ('Listen %s:%d' % (addr, port)) in site.decode('utf8', 'replace').splitlines():
            return True
    return ctx.port_free(bind.strip('[]'), port)


def ddns_overlap(hostname, ddclient_text):
    """True if `hostname` is in the ddclient host list (ddclient would fight the tunnel's CNAME)."""
    host = hostname.lower().rstrip('.')
    for line in (ddclient_text or '').splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        for tok in re.split(r'[,\s]+', line):
            if '=' not in tok and tok.lower().rstrip('.') == host:
                return True
    return False


class CloudProvisioner(object):
    """Automatic path: finds/creates the tunnel, ingress rules and DNS record through the API."""

    def __init__(self, ctx, api, st, hostname, name, bind, port):
        self.ctx, self.api, self.st = ctx, api, st
        self.hostname, self.name, self.bind, self.port = hostname, name, bind, port
        self.t = st['tunnel']
        self.account_id = None
        self.zone_id = None
        self.tunnel_id = None

    @property
    def origin_service(self):
        return 'http://%s:%d' % ('[%s]' % self.bind.strip('[]') if ':' in self.bind else self.bind, self.port)

    def _placeholder(self):
        return self.tunnel_id == PLACEHOLDER_ID

    def resolve_zone(self):
        labels = self.hostname.split('.')
        for i in range(len(labels) - 1):
            zone = '.'.join(labels[i:])
            res = self.api.get('/zones', {'name': zone})
            if res:
                self.zone_id = res[0]['id']
                self.account_id = (res[0].get('account') or {}).get('id')
                if not self.account_id:
                    raise SetupError('Could not determine the Cloudflare account id for zone %s.' % zone)
                self.ctx.ui.say('Found Cloudflare zone %s.' % zone)
                return
        raise SetupError('No Cloudflare zone found for %s that this API token can see. The domain must be on '
                         'Cloudflare, and the token needs Zone:Read for it.' % self.hostname)

    def ensure_tunnel(self):
        base = '/accounts/%s/cfd_tunnel' % self.account_id
        found = [x for x in self.api.get(base, {'name': self.name, 'is_deleted': 'false'})
                 if x.get('name') == self.name and not x.get('deleted_at')]
        if found:
            tun = found[0]
            if tun.get('config_src') != 'cloudflare':
                raise ConflictError('A tunnel named %r exists but is locally managed (config file), so its ingress '
                                    'cannot be set through the API. Pick another tunnel name.' % self.name)
            self.tunnel_id = tun['id']
            created = self.t.get('created_tunnel') and self.t.get('id') == self.tunnel_id
            self.ctx.ui.say('Using existing tunnel %r.' % self.name)
        else:
            res = self.api.mutate('POST', base, {'name': self.name, 'config_src': 'cloudflare'}, {'id': PLACEHOLDER_ID})
            self.tunnel_id = res['id']
            created = True
            self.ctx.did('Created tunnel %r.' % self.name, 'create tunnel %r.' % self.name)
        self.t.update({'id': self.tunnel_id, 'name': self.name, 'account_id': self.account_id,
                       'zone_id': self.zone_id, 'created_tunnel': bool(created)})
        save_state(self.ctx, self.st)

    def ensure_ingress(self):
        path = '/accounts/%s/cfd_tunnel/%s/configurations' % (self.account_id, self.tunnel_id)
        cfg = {} if self._placeholder() else ((self.api.get(path) or {}).get('config') or {})
        rules = list(cfg.get('ingress') or [])
        ours = {'hostname': self.hostname, 'service': self.origin_service}
        catch_all = [r for r in rules if not r.get('hostname')]
        others = [r for r in rules if r.get('hostname') and r['hostname'].lower() != self.hostname]
        previous = [r for r in rules if r.get('hostname', '').lower() == self.hostname]
        foreign = [r for r in others]
        if foreign:
            self.ctx.ui.warn('This tunnel already has other ingress rules. They are KEPT unchanged; only the rule for %s is added/updated:' % self.hostname)
            for r in foreign:
                self.ctx.ui.say('    %s -> %s' % (r.get('hostname'), r.get('service')))
        new_rules, replaced = [], False
        for r in rules:
            if r.get('hostname', '').lower() == self.hostname:
                if not replaced:
                    new_rules.append(dict(r, **ours) if previous else ours)
                    replaced = True
            elif r.get('hostname'):
                new_rules.append(r)
        if not replaced:
            new_rules.append(ours)
        new_rules.append(catch_all[0] if catch_all else {'service': 'http_status:404'})
        if new_rules == rules:
            self.ctx.ui.say('Tunnel ingress already up to date.')
            return
        new_cfg = dict(cfg, ingress=new_rules)
        self.api.mutate('PUT', path, {'config': new_cfg}, {})
        self.ctx.did('Set tunnel ingress: %s -> %s' % (self.hostname, self.origin_service),
                     'set tunnel ingress: %s -> %s' % (self.hostname, self.origin_service))

    def ensure_dns(self):
        want = '%s.cfargotunnel.com' % self.tunnel_id
        base = '/zones/%s/dns_records' % self.zone_id
        recs = self.api.get(base, {'name': self.hostname})
        conflicts = []
        mine = None
        for r in recs:
            if r.get('type') == 'CNAME' and (r.get('content') or '').lower() == want.lower() and mine is None:
                mine = r
            elif r.get('type') in ('A', 'AAAA', 'CNAME'):
                conflicts.append(r)
        if conflicts:
            self.ctx.ui.warn('A DNS record for %s already exists and is not this tunnel\'s:' % self.hostname)
            for r in conflicts:
                self.ctx.ui.say('    %s %s -> %s (proxied=%s)' % (r.get('type'), r.get('name'), r.get('content'), r.get('proxied')))
            if not self.ctx.force:
                raise ConflictError('Refusing to overwrite it. Remove it yourself, or re-run with --force to replace it.')
            for r in conflicts:
                self.api.mutate('DELETE', '%s/%s' % (base, r['id']))
        if mine is not None:
            if not mine.get('proxied'):
                self.api.mutate('PATCH', '%s/%s' % (base, mine['id']), {'proxied': True}, {})
            self.t['dns_record_id'] = mine['id']
            self.t.setdefault('dns_created', False)
            self.ctx.ui.say('DNS record for %s already points at the tunnel.' % self.hostname)
        else:
            res = self.api.mutate('POST', base, {'type': 'CNAME', 'name': self.hostname, 'content': want, 'proxied': True,
                                                 'ttl': 1, 'comment': DNS_COMMENT}, {'id': '<new-record-id>'})
            self.t['dns_record_id'] = res['id']
            self.t['dns_created'] = True
            self.ctx.did('Created proxied CNAME %s -> %s' % (self.hostname, want),
                         'create proxied CNAME %s -> %s' % (self.hostname, want))
        self.t['dns_content'] = want
        save_state(self.ctx, self.st)

    def fetch_token(self):
        if self._placeholder():
            return None
        return self.api.get('/accounts/%s/cfd_tunnel/%s/token' % (self.account_id, self.tunnel_id))

    def run(self):
        self.resolve_zone()
        self.ensure_tunnel()
        self.ensure_ingress()
        self.ensure_dns()
        return self.fetch_token()


def _origin_url(bind, port):
    return 'http://%s:%d/knock_knock.txt' % ('[%s]' % bind.strip('[]') if ':' in bind else bind, port)


def verify(ctx, hostname, bind, port, access_enabled, api=None, account_id=None, tunnel_id=None):
    """Returns list of (label, ok, detail). Never raises for a failed check."""
    results = []
    if ctx.dry_run:
        ctx.ui.say('[dry-run] would verify service, tunnel health, origin and public hostname.')
        return results
    ok = False
    for i in range(6):
        out = ctx.runner.run(['systemctl', 'is-active', SERVICE_NAME], check=False, read_only=True).stdout.strip()
        ok = out == 'active'
        if ok:
            break
        ctx.sleep(2)
    results.append(('cloudflared service active', ok, '' if ok else 'try: sudo journalctl -u %s -n 50' % SERVICE_NAME))

    def fetch(url, headers=None, follow=True):
        try:
            return ctx.http.request('GET', url, headers=headers or {}, follow_redirects=follow)
        except SetupError as e:
            return str(e)

    jwt = {'Cf-Access-Jwt-Assertion': 'local-check'} if access_enabled else {}
    r = fetch(_origin_url(bind, port), dict(jwt, Host=hostname))
    good = not isinstance(r, str) and r.status == 200 and r.body.decode('utf8', 'replace').startswith('hello?')
    results.append(('local origin answers for ' + hostname, good, r if isinstance(r, str) else 'HTTP %d' % r.status))
    if access_enabled:
        r = fetch(_origin_url(bind, port), {'Host': hostname})
        good = not isinstance(r, str) and r.status == 403
        results.append(('origin refuses requests without an Access header', good, r if isinstance(r, str) else 'HTTP %d' % r.status))

    if api and account_id and tunnel_id:
        healthy, detail = False, ''
        for i in range(8):
            try:
                tun = api.get('/accounts/%s/cfd_tunnel/%s' % (account_id, tunnel_id)) or {}
                detail = 'status=%s' % tun.get('status')
                healthy = tun.get('status') in ('healthy', 'degraded')
            except SetupError as e:
                detail = str(e)
            if healthy:
                break
            ctx.sleep(min(2 ** i, 10))
        results.append(('tunnel connected to Cloudflare', healthy, detail))

    good, detail = False, ''
    for i in range(6):
        r = fetch('https://%s/knock_knock.txt' % hostname, follow=False)
        if isinstance(r, str):
            detail = r
        else:
            detail = 'HTTP %d' % r.status
            if access_enabled:
                good = r.status in (301, 302, 303, 307, 308, 401, 403)
            else:
                good = r.status == 200 and r.body.decode('utf8', 'replace').startswith('hello?')
        if good:
            break
        ctx.sleep(min(2 ** i, 10))
    label = 'https://%s responds' % hostname + (' (protected by Access)' if access_enabled else '')
    results.append((label, good, detail))
    return results


def remove(ctx, st, api=None):
    """Tear down what the state file says the wizard created. Returns list of human-readable lines."""
    t, notes = st.get('tunnel', {}), []
    if remove_service(ctx):
        notes.append('Removed %s service and %s' % (SERVICE_NAME, ENV_PATH))
    if apache.remove_tunnel_site(ctx):
        notes.append('Removed Apache vhost %s' % apache.TUNNEL_SITE_PATH)
    if api and t.get('account_id'):
        acct = t['account_id']
        if t.get('dns_created') and t.get('dns_record_id') and t.get('zone_id'):
            try:
                rec = api.get('/zones/%s/dns_records/%s' % (t['zone_id'], t['dns_record_id']))
                if rec and rec.get('type') == 'CNAME' and (rec.get('content') or '').lower() == (t.get('dns_content') or '').lower():
                    api.mutate('DELETE', '/zones/%s/dns_records/%s' % (t['zone_id'], t['dns_record_id']))
                    notes.append('Deleted DNS record %s' % t.get('hostname'))
                else:
                    notes.append('LEFT ALONE: DNS record %s no longer points at our tunnel' % t.get('hostname'))
            except ApiError as e:
                notes.append('DNS record not deleted (%s)' % e)
        if t.get('created_tunnel') and t.get('id'):
            base = '/accounts/%s/cfd_tunnel/%s' % (acct, t['id'])
            try:
                api.mutate('DELETE', base + '/connections')
                api.mutate('DELETE', base)
                notes.append('Deleted tunnel %s' % t.get('name'))
            except ApiError as e:
                notes.append('Tunnel not deleted (%s)' % e)
        elif t.get('id'):
            notes.append('LEFT ALONE: tunnel %s (not created by this wizard)' % t.get('name'))
    elif t.get('dns_created') or t.get('created_tunnel'):
        notes.append('LEFT IN CLOUDFLARE (no API token given): DNS record %s and tunnel %s; delete them in the dashboard.' % (t.get('hostname'), t.get('name')))
    return notes
